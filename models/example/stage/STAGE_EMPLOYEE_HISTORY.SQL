SELECT J.JOB_TITLE,D.DEPARTMENT_NAME,CONCAT(E.FIRST_NAME,'::', E.LAST_NAME) as full_name 
FROM {{ ref('RAW_EMPLOYEES') }} E
INNER JOIN
{{ ref('RAW_JOB_HISTORY') }} JH
ON E.EMPLOYEE_ID=JH.EMPLOYEE_ID
AND JH.START_DATE BETWEEN '2023-01-15' AND '2024-05-23'
INNER JOIN {{ ref('raw_jobs') }} ON J.JOB_ID=JH.JOB_ID
INNER JOIN {{ ref('RAW_DEPARTMENTS') }} D ON D.DEPARTMENT_ID=jh.DEPARTMENT_ID
